/**
 * Apply step.
 *
 * Runs after the agent process has exited, with the GitHub App token. It turns
 * triage/gh-<n>/result.json into a commit, branch, pull request, comment, and
 * labels. The agent never sees this token.
 */

import { join } from 'node:path';

import { readResult } from './agent.mjs';
import { buildComment, buildPrBody, buildPrTitle } from './comment.mjs';
import {
	addLabels,
	changedFiles,
	checkoutBranch,
	commitAll,
	createPullRequest,
	currentBranch,
	deleteBranch,
	diffStat,
	fetchIssue,
	findPullRequest,
	postComment,
	pushBranch,
	resetSoft,
	swapLabel,
} from './github.mjs';
import { LABELS, currentTriageLabel, labelForResult } from './router.mjs';
import {
	assertChangeset,
	assertNoSecrets,
	assertSafeChanges,
	readEvent,
	readOptional,
	redact,
	required,
	runUrl,
	when,
} from './util.mjs';

const cwd = process.cwd();
let failureContext = null;

async function readJson(path) {
	const raw = await readOptional(path);
	if (!raw) {
		return null;
	}
	try {
		return JSON.parse(raw);
	} catch (error) {
		throw new Error(`${path} is not valid JSON: ${error.message}`, { cause: error });
	}
}

function messageOf(error) {
	if (error instanceof Error) {
		return error.stack ?? error.message;
	}
	return String(error);
}

function errorText(error, secrets) {
	return redact(messageOf(error), secrets).slice(-12_000);
}

function failureBody(error, secrets) {
	const url = runUrl();
	return [
		'<!-- triagebot:triage-failed -->',
		'Automated triage failed while processing this issue.',
		'',
		...when(url, `Run: ${url}`),
		...when(url, ''),
		'<details>',
		'<summary><em>Error</em></summary>',
		'',
		'```',
		errorText(error, secrets),
		'```',
		'',
		'</details>',
		'',
		'A maintainer can retry by commenting with new information, or by setting `triage: needs triage` and commenting.',
		'',
		'_This comment was generated by the triage bot._',
	].join('\n');
}

async function reportFailure(error, secrets) {
	if (!failureContext) {
		console.error(error);
		return;
	}
	const { repo, issueNumber, currentLabel, writeToken } = failureContext;
	try {
		await postComment(repo, issueNumber, failureBody(error, secrets), writeToken);
		await swapLabel(repo, issueNumber, currentLabel, LABELS.failed, writeToken);
	} catch (commentError) {
		console.error('Could not record the triage failure:', commentError);
	}
}

async function readAgentResult(triageDir) {
	const agentError = await readOptional(join(triageDir, 'error.txt'));
	if (agentError) {
		throw new Error(agentError.replace(/^Error:\s*/, ''));
	}
	return readResult(triageDir);
}

async function prepareBranch(branch, decision) {
	const current = await currentBranch(cwd);
	if (decision.startBranch && current !== decision.startBranch && current !== branch) {
		throw new Error(
			`The agent left the repository on "${current}" instead of "${decision.startBranch}". Refusing to apply the result.`
		);
	}
	await checkoutBranch(cwd, branch);
	// Collapse any commits the agent made into a single bot commit. This also
	// keeps a secret that was committed and then removed out of the pushed
	// history.
	await resetSoft(cwd, 'main');
}

function canFixResult(result) {
	return (
		result.fixed && result.reproducible && !result.skipped && result.verdict !== 'intended-behavior'
	);
}

async function collectChanges({ result, apiKey, writeToken, readToken }) {
	const files = await changedFiles(cwd);
	const secrets = [apiKey, writeToken, readToken].filter(Boolean);
	const canFix = canFixResult(result);
	assertSafeChanges(files);
	assertChangeset({ ...result, fixed: canFix }, files);
	await assertNoSecrets(files, secrets);
	return { files, secrets, canFix };
}

async function prepareTriage({ branch, decision, triageDir, apiKey, writeToken, readToken }) {
	const result = await readAgentResult(triageDir);
	await prepareBranch(branch, decision);
	const { files, secrets, canFix } = await collectChanges({
		result,
		apiKey,
		writeToken,
		readToken,
	});
	const report = (await readOptional(join(triageDir, 'report.md'))) ?? '';
	const commentDraft = await readOptional(join(triageDir, 'comment.md'));
	const prDraft = await readOptional(join(triageDir, 'pr.md'));
	return { result, files, secrets, canFix, report, commentDraft, prDraft };
}

async function openPullRequest({
	repo,
	branch,
	result,
	files,
	issueDetails,
	prDraft,
	secrets,
	readToken,
	writeToken,
}) {
	const draftStat = await diffStat(cwd);
	const prTitle = redact(
		buildPrTitle({ result, issue: issueDetails, changedFiles: files }),
		secrets
	);
	const prBody = redact(
		buildPrBody({
			result,
			issue: issueDetails,
			changedFiles: files,
			diffStat: draftStat,
			draft: prDraft,
		}),
		secrets
	);
	const pr =
		(await findPullRequest(repo, branch, readToken)) ??
		(await createPullRequest(
			repo,
			{ title: prTitle, body: prBody, head: branch, base: 'main' },
			writeToken
		));
	try {
		await addLabels(repo, pr.number, ['fix verified'], writeToken);
	} catch (error) {
		console.warn(`Could not label PR #${pr.number}: ${error.message}`);
	}
	return pr;
}

function noFilesNote(result, canFix) {
	if (canFix) {
		return 'The agent reported a fix but produced no diff, so no pull request was opened.';
	}
	if (result.fixed) {
		return 'The agent reported a fix, but the result was skipped, not reproducible, or intended behavior, so no pull request was opened.';
	}
	return null;
}

function fallbackMessage(canFix) {
	return canFix
		? 'fix(auto-triage): automated fix'
		: 'test(auto-triage): failing test and investigation notes';
}

async function publishChanges({
	repo,
	branch,
	result,
	files,
	canFix,
	issueDetails,
	prDraft,
	secrets,
	readToken,
	writeToken,
}) {
	if (files.length === 0) {
		return { branchPushed: false, pr: null, note: noFilesNote(result, canFix) };
	}

	const commitMessage = redact(result.commitMessage ?? fallbackMessage(canFix), secrets);
	await commitAll(cwd, commitMessage);
	await pushBranch({ cwd, repo, branch, token: writeToken });

	const pr = canFix
		? await openPullRequest({
				repo,
				branch,
				result,
				files,
				issueDetails,
				prDraft,
				secrets,
				readToken,
				writeToken,
			})
		: null;
	return { branchPushed: true, pr, note: null };
}

async function applyOptionalLabels(repo, issueNumber, result, writeToken) {
	const labels = [result.priority, ...(result.packages ?? [])].filter(Boolean);
	if (labels.length === 0) {
		return;
	}
	try {
		await addLabels(repo, issueNumber, labels, writeToken);
	} catch (error) {
		console.warn(`Could not add optional labels: ${error.message}`);
	}
}

async function postTriageComment({
	repo,
	issueNumber,
	result,
	fixedWithDiff,
	branchPushed,
	branch,
	pr,
	report,
	commentDraft,
	model,
	note,
	secrets,
	writeToken,
}) {
	const comment = redact(
		buildComment({
			result: { ...result, fixed: fixedWithDiff },
			report,
			branch: branchPushed ? branch : null,
			pr,
			repo,
			model,
			note,
			draft: commentDraft,
		}),
		secrets
	);
	await postComment(repo, issueNumber, comment, writeToken);
}

async function updateIssue({
	repo,
	issueNumber,
	currentLabel,
	result,
	canFix,
	branchPushed,
	branch,
	pr,
	report,
	commentDraft,
	model,
	note,
	secrets,
	writeToken,
}) {
	const fixedWithDiff = canFix && branchPushed;
	const nextLabel = labelForResult({ ...result, fixed: fixedWithDiff }, { prOpened: Boolean(pr) });
	await swapLabel(repo, issueNumber, currentLabel, nextLabel, writeToken);
	if (failureContext) {
		failureContext.currentLabel = nextLabel;
	}
	await applyOptionalLabels(repo, issueNumber, result, writeToken);
	await postTriageComment({
		repo,
		issueNumber,
		result,
		fixedWithDiff,
		branchPushed,
		branch,
		pr,
		report,
		commentDraft,
		model,
		note,
		secrets,
		writeToken,
	});
	return nextLabel;
}

async function applyTriage({
	repo,
	issueNumber,
	currentLabel,
	readToken,
	writeToken,
	model,
	apiKey,
	issueDetails,
	decision,
}) {
	const branch = `triagebot/fix-${issueNumber}`;
	const triageDir = join('triage', `gh-${issueNumber}`);
	const prepared = await prepareTriage({
		branch,
		decision,
		triageDir,
		apiKey,
		writeToken,
		readToken,
	});
	const published = await publishChanges({
		repo,
		branch,
		result: prepared.result,
		files: prepared.files,
		canFix: prepared.canFix,
		issueDetails,
		prDraft: prepared.prDraft,
		secrets: prepared.secrets,
		readToken,
		writeToken,
	});
	const nextLabel = await updateIssue({
		repo,
		issueNumber,
		currentLabel,
		result: prepared.result,
		canFix: prepared.canFix,
		branchPushed: published.branchPushed,
		branch,
		pr: published.pr,
		report: prepared.report,
		commentDraft: prepared.commentDraft,
		model,
		note: published.note,
		secrets: prepared.secrets,
		writeToken,
	});
	console.log(`Triage finished for #${issueNumber}: ${nextLabel}`);
}

async function readDecision(triageDir) {
	const decision = await readJson(join(triageDir, 'decision.json'));
	if (decision) {
		return decision;
	}
	const agentError = await readOptional(join(triageDir, 'error.txt'));
	throw new Error(agentError ?? 'The triage agent did not produce decision.json.');
}

async function handleSkip({ issueNumber, decision }) {
	console.log(`Skipping #${issueNumber}: ${decision.reason ?? 'no action'}`);
}

async function handleCleanup({ repo, issueNumber, writeToken }) {
	await deleteBranch(repo, `triagebot/fix-${issueNumber}`, writeToken);
}

async function handleTriage({
	repo,
	issueNumber,
	currentLabel,
	readToken,
	writeToken,
	model,
	apiKey,
	decision,
}) {
	const triageDir = join('triage', `gh-${issueNumber}`);
	const issueDetails =
		(await readJson(join(triageDir, 'issue.json'))) ??
		(await fetchIssue(repo, issueNumber, readToken));

	await applyTriage({
		repo,
		issueNumber,
		currentLabel: decision.currentLabel ?? currentLabel,
		readToken,
		writeToken,
		model,
		apiKey,
		issueDetails,
		decision,
	});
}

const DECISION_HANDLERS = {
	skip: handleSkip,
	cleanup: handleCleanup,
	triage: handleTriage,
};

async function handleDecision(context) {
	const handler = DECISION_HANDLERS[context.decision.type];
	if (!handler) {
		throw new Error(`Unsupported decision type: ${context.decision.type}`);
	}
	await handler(context);
}

async function main() {
	const repo = required('GITHUB_REPOSITORY');
	const eventPath = required('GITHUB_EVENT_PATH');
	const writeToken = required('TRIAGE_WRITE_TOKEN');
	const readToken = required('GITHUB_TOKEN');
	const model = required('TRIAGE_MODEL');
	const apiKey = process.env.TRIAGE_MODEL_API_KEY ?? '';

	const { issue } = await readEvent(eventPath);
	if (!issue) {
		console.log('No issue in the event payload; nothing to do.');
		return;
	}

	const issueNumber = issue.number;
	const triageDir = join('triage', `gh-${issueNumber}`);
	const currentLabel = currentTriageLabel(issue);
	failureContext = { repo, issueNumber, currentLabel, writeToken };

	const decision = await readDecision(triageDir);
	failureContext.currentLabel = decision.currentLabel ?? currentLabel;

	await handleDecision({
		decision,
		repo,
		issueNumber,
		currentLabel,
		readToken,
		writeToken,
		model,
		apiKey,
	});
}

try {
	await main();
} catch (error) {
	const secrets = [
		process.env.TRIAGE_MODEL_API_KEY,
		process.env.TRIAGE_WRITE_TOKEN,
		process.env.GITHUB_TOKEN,
	].filter(Boolean);
	console.error(redact(error?.stack ?? String(error), secrets));
	await reportFailure(error, secrets);
	process.exitCode = 1;
}

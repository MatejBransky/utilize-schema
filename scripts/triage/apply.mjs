/**
 * Apply step.
 *
 * Runs after the agent process has exited, with the GitHub App token. It turns
 * triage/gh-<n>/result.json into a commit, branch, pull request, comment, and
 * labels. The agent never sees this token.
 */

import { readFile } from 'node:fs/promises';
import { join } from 'node:path';

import { readResult } from './agent.mjs';
import { buildComment, buildPrBody, buildPrTitle } from './comment.mjs';
import * as gh from './github.mjs';
import { LABELS, currentTriageLabel, labelForResult } from './router.mjs';
import {
	assertChangeset,
	assertNoSecrets,
	assertSafeChanges,
	readOptional,
	redact,
	required,
	runUrl,
} from './util.mjs';

const cwd = process.cwd();
let failureContext = null;

async function readJson(path) {
	const raw = await readOptional(path);
	if (!raw) return null;
	try {
		return JSON.parse(raw);
	} catch (error) {
		throw new Error(`${path} is not valid JSON: ${error.message}`);
	}
}

async function reportFailure(error, secrets) {
	if (!failureContext) {
		console.error(error);
		return;
	}
	const { repo, issueNumber, currentLabel, writeToken } = failureContext;
	const url = runUrl();
	const message = redact(error?.stack ?? error?.message ?? String(error), secrets);
	const body = [
		'<!-- triagebot:triage-failed -->',
		'Automated triage failed while processing this issue.',
		'',
		...(url ? [`Run: ${url}`, ''] : []),
		'<details>',
		'<summary><em>Error</em></summary>',
		'',
		'```',
		message.slice(-12_000),
		'```',
		'',
		'</details>',
		'',
		'A maintainer can retry by commenting with new information, or by setting `triage: needs triage` and commenting.',
		'',
		'_This comment was generated by the triage bot._',
	].join('\n');
	try {
		await gh.postComment(repo, issueNumber, body, writeToken);
		await gh.swapLabel(repo, issueNumber, currentLabel, LABELS.failed, writeToken);
	} catch (commentError) {
		console.error('Could not record the triage failure:', commentError);
	}
}

async function applyTriage({
	repo,
	issueNumber,
	currentLabel,
	readToken,
	writeToken,
	model,
	apiKey,
	issueDetails,
	decision,
}) {
	const branch = `triagebot/fix-${issueNumber}`;
	const triageDir = join('triage', `gh-${issueNumber}`);

	const agentError = await readOptional(join(triageDir, 'error.txt'));
	if (agentError) throw new Error(agentError.replace(/^Error:\s*/, ''));

	const result = await readResult(triageDir);
	const current = await gh.currentBranch(cwd);
	if (decision.startBranch && current !== decision.startBranch && current !== branch) {
		throw new Error(
			`The agent left the repository on "${current}" instead of "${decision.startBranch}". Refusing to apply the result.`
		);
	}

	await gh.checkoutBranch(cwd, branch);
	// Collapse any commits the agent made into a single bot commit. This also
	// keeps a secret that was committed and then removed out of the pushed
	// history.
	await gh.resetSoft(cwd, 'main');

	const files = await gh.changedFiles(cwd);
	const secrets = [apiKey, writeToken, readToken].filter(Boolean);
	const canFix =
		result.fixed &&
		result.reproducible &&
		!result.skipped &&
		result.verdict !== 'intended-behavior';
	assertSafeChanges(files);
	assertChangeset({ ...result, fixed: canFix }, files);
	await assertNoSecrets(files, secrets);

	const report = (await readOptional(join(triageDir, 'report.md'))) ?? '';
	const commentDraft = await readOptional(join(triageDir, 'comment.md'));
	const prDraft = await readOptional(join(triageDir, 'pr.md'));

	let branchPushed = false;
	let pr = null;
	let note = null;

	if (files.length > 0) {
		const commitMessage = redact(
			result.commitMessage ??
				(canFix
					? 'fix(auto-triage): automated fix'
					: 'test(auto-triage): failing test and investigation notes'),
			secrets
		);
		await gh.commitAll(cwd, commitMessage);
		await gh.pushBranch({ cwd, repo, branch, token: writeToken });
		branchPushed = true;

		if (canFix) {
			const draftStat = await gh.diffStat(cwd);
			const prTitle = redact(
				buildPrTitle({ result, issue: issueDetails, changedFiles: files }),
				secrets
			);
			const prBody = redact(
				buildPrBody({
					result,
					issue: issueDetails,
					changedFiles: files,
					diffStat: draftStat,
					draft: prDraft,
				}),
				secrets
			);
			pr =
				(await gh.findPullRequest(repo, branch, readToken)) ??
				(await gh.createPullRequest(
					repo,
					{
						title: prTitle,
						body: prBody,
						head: branch,
						base: 'main',
					},
					writeToken
				));
			try {
				await gh.addLabels(repo, pr.number, ['fix verified'], writeToken);
			} catch (error) {
				console.warn(`Could not label PR #${pr.number}: ${error.message}`);
			}
		}
	} else if (canFix) {
		note = 'The agent reported a fix but produced no diff, so no pull request was opened.';
	} else if (result.fixed) {
		note =
			'The agent reported a fix, but the result was skipped, not reproducible, or intended behavior, so no pull request was opened.';
	}

	const fixedWithDiff = canFix && branchPushed;
	const nextLabel = labelForResult({ ...result, fixed: fixedWithDiff }, { prOpened: Boolean(pr) });

	await gh.swapLabel(repo, issueNumber, currentLabel, nextLabel, writeToken);
	if (failureContext) failureContext.currentLabel = nextLabel;

	const optionalLabels = [result.priority, ...(result.packages ?? [])].filter(Boolean);
	if (optionalLabels.length > 0) {
		try {
			await gh.addLabels(repo, issueNumber, optionalLabels, writeToken);
		} catch (error) {
			console.warn(`Could not add optional labels: ${error.message}`);
		}
	}

	const comment = redact(
		buildComment({
			result: { ...result, fixed: fixedWithDiff },
			report,
			branch: branchPushed ? branch : null,
			pr,
			repo,
			model,
			note,
			draft: commentDraft,
		}),
		secrets
	);
	await gh.postComment(repo, issueNumber, comment, writeToken);
	console.log(`Triage finished for #${issueNumber}: ${nextLabel}`);
}

async function main() {
	const repo = required('GITHUB_REPOSITORY');
	const eventPath = required('GITHUB_EVENT_PATH');
	const writeToken = required('TRIAGE_WRITE_TOKEN');
	const readToken = required('GITHUB_TOKEN');
	const model = required('TRIAGE_MODEL');
	const apiKey = process.env.TRIAGE_MODEL_API_KEY ?? '';

	const payload = JSON.parse(await readFile(eventPath, 'utf8'));
	const issue = payload.issue;
	if (!issue) {
		console.log('No issue in the event payload; nothing to do.');
		return;
	}

	const issueNumber = issue.number;
	const triageDir = join('triage', `gh-${issueNumber}`);
	const currentLabel = currentTriageLabel(issue);
	failureContext = { repo, issueNumber, currentLabel, writeToken };

	const decision = await readJson(join(triageDir, 'decision.json'));
	if (!decision) {
		const agentError = await readOptional(join(triageDir, 'error.txt'));
		throw new Error(agentError ?? 'The triage agent did not produce decision.json.');
	}
	failureContext.currentLabel = decision.currentLabel ?? currentLabel;

	if (decision.type === 'skip') {
		console.log(`Skipping #${issueNumber}: ${decision.reason ?? 'no action'}`);
		return;
	}
	if (decision.type === 'cleanup') {
		await gh.deleteBranch(repo, `triagebot/fix-${issueNumber}`, writeToken);
		return;
	}
	if (decision.type !== 'triage') {
		throw new Error(`Unsupported decision type: ${decision.type}`);
	}

	const issueDetails =
		(await readJson(join(triageDir, 'issue.json'))) ??
		(await gh.fetchIssue(repo, issueNumber, readToken));

	await applyTriage({
		repo,
		issueNumber,
		currentLabel: decision.currentLabel ?? currentLabel,
		readToken,
		writeToken,
		model,
		apiKey,
		issueDetails,
		decision,
	});
}

main().catch(async (error) => {
	const secrets = [
		process.env.TRIAGE_MODEL_API_KEY,
		process.env.TRIAGE_WRITE_TOKEN,
		process.env.GITHUB_TOKEN,
	].filter(Boolean);
	console.error(redact(error?.stack ?? String(error), secrets));
	await reportFailure(error, secrets);
	process.exitCode = 1;
});

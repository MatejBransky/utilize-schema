/**
 * Helpers shared by the runtime packages' baseline scripts. They collect the
 * failing suite cases of every measured dialect and render the generated
 * `knownFailuresByDialect.ts` module the package commits.
 */

import { remainingRuntimeFailures2019 } from '../packages/test-utils/src/suite/remainingRuntimeFailures.ts';

const RENDER_INDENT = '\t\t';
const SHARED_FAILURES = { '2019-09': remainingRuntimeFailures2019 };

/**
 * @param {Record<string, string[]>} failuresByDialect
 * @param {string} generatedBy Command that regenerates the file.
 */
export function renderDialectFailures(failuresByDialect, generatedBy) {
	const sharedByDialect = {};

	for (const [dialect, sharedFailures] of Object.entries(SHARED_FAILURES)) {
		const present = sharedFailures.filter((failure) =>
			failuresByDialect[dialect]?.includes(failure)
		);

		if (present.length > 0 && present.length !== sharedFailures.length) {
			throw new Error(
				`Update remainingRuntimeFailures.ts: ${sharedFailures.length - present.length} shared ${dialect} failures now pass.`
			);
		}

		if (present.length > 0) {
			sharedByDialect[dialect] = present;
		}
	}

	const sharedImport =
		Object.keys(sharedByDialect).length === 0
			? ''
			: "import { remainingRuntimeFailures2019 } from '@utilize/test-utils/suite/remainingRuntimeFailures';\n\n";

	const body = Object.entries(failuresByDialect)
		.map(([dialect, failing]) => {
			const shared = sharedByDialect[dialect] ?? [];
			const remaining = failing.filter((failure) => !shared.includes(failure));
			const entries = [shared.length === 0 ? '' : '\t\t...remainingRuntimeFailures2019,']
				.concat(renderList(remaining))
				.filter((line) => line !== '')
				.join('\n');

			return `\t${JSON.stringify(dialect)}: [\n${entries}\n\t],`;
		})
		.join('\n');

	// An empty dialect keeps its `string[]` type; `satisfies` would infer `never[]`.
	return `// Generated by \`${generatedBy}\`; do not edit by hand.
${sharedImport}export type KnownFailuresByDialect = Record<
	'draft-04' | 'draft-06' | 'draft-07' | '2019-09' | '2020-12',
	string[]
>;

export const knownFailuresByDialect: KnownFailuresByDialect = {
${body}
};
`;
}

function renderList(values) {
	return values.map((value) => `${RENDER_INDENT}${JSON.stringify(value)},`).join('\n');
}

/**
 * `options` carries the loaded suite files, the dialect tokens, and the
 * package-specific `compile`/`accepts` closures. The shapes are documented on
 * suite loader types in the test-utils package; they stay untyped here so this
 * script has no workspace dependency of its own.
 */
export async function collectDialectFailures({
	files,
	dialects,
	isCompatible,
	suiteCaseKey,
	compile,
	accepts,
}) {
	const failuresByDialect = {};

	for (const [dialect, token] of Object.entries(dialects)) {
		failuresByDialect[dialect] = await failingCasesFor({
			files,
			token,
			dialect,
			isCompatible,
			suiteCaseKey,
			compile,
			accepts,
		});
	}

	return failuresByDialect;
}

async function failingCasesFor(options) {
	const failing = [];

	for (const file of options.files) {
		failing.push(...(await failingInFile({ ...options, file })));
	}

	return failing.sort();
}

async function failingInFile({
	file,
	token,
	dialect,
	isCompatible,
	suiteCaseKey,
	compile,
	accepts,
}) {
	const failing = [];

	for (const testCase of file.cases) {
		if (!isCompatible(testCase.compatibility, token)) {
			continue;
		}

		const failed = await failedInstances(testCase, dialect, compile, accepts);

		if (failed > 0) {
			failing.push(`${suiteCaseKey(file, testCase)} (${failed} failed)`);
		}
	}

	return failing;
}

async function failedInstances(testCase, dialect, compile, accepts) {
	try {
		const schema = await compile(testCase, dialect);

		return testCase.tests.filter((suiteTest) => accepts(schema, suiteTest.data) !== suiteTest.valid)
			.length;
	} catch {
		return testCase.tests.length;
	}
}

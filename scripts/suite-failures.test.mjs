import assert from 'node:assert/strict';
import test from 'node:test';

import { remainingRuntimeFailures2019 } from '../packages/test-utils/src/suite/remainingRuntimeFailures.ts';

import { collectDialectFailures, renderDialectFailures } from './suite-failures.mjs';

const files = [
	{
		name: 'sample.json',
		cases: [
			{
				compatibility: undefined,
				tests: [
					{ valid: true, data: 'valid' },
					{ valid: false, data: 'invalid-a' },
					{ valid: false, data: 'invalid-b' },
				],
			},
			{
				compatibility: 7,
				tests: [
					{ valid: true, data: 'draft-07 valid' },
					{ valid: false, data: 'draft-07 invalid' },
				],
			},
			{
				compatibility: undefined,
				tests: [{ valid: true, data: 'compile' }],
			},
		],
	},
];

void test('collectDialectFailures reports the failing instances of every dialect', async () => {
	const failures = await collectDialectFailures({
		files,
		dialects: { 'draft-04': 4, 'draft-07': 7 },
		isCompatible: (compatibility, token) => compatibility === undefined || compatibility === token,
		suiteCaseKey: (file, testCase) => `${file.name} :: ${testCase.tests[0].data}`,
		compile: async (testCase) => {
			if (testCase.compatibility === undefined && testCase.tests.length === 1) {
				throw new Error('cannot compile');
			}

			return testCase;
		},
		accepts: () => true,
	});

	assert.deepEqual(failures, {
		'draft-04': ['sample.json :: compile (1 failed)', 'sample.json :: valid (2 failed)'],
		'draft-07': [
			'sample.json :: compile (1 failed)',
			'sample.json :: draft-07 valid (1 failed)',
			'sample.json :: valid (2 failed)',
		],
	});
});

void test('renderDialectFailures renders the generated module', () => {
	const source = renderDialectFailures(
		{ 'draft-04': ['sample.json :: case (1 failed)'] },
		'node script.mjs'
	);

	assert.match(source, /^\/\/ Generated by `node script\.mjs`; do not edit by hand\./);
	assert.match(source, /export const knownFailuresByDialect: KnownFailuresByDialect = \{/);
	assert.match(source, /\t"draft-04": \[\n\t\t"sample\.json :: case \(1 failed\)",\n\t\],/);
	assert.match(source, /\};\n$/);
});

void test('renderDialectFailures shares the remaining runtime failures', () => {
	const source = renderDialectFailures(
		{ '2019-09': [...remainingRuntimeFailures2019, 'sample.json :: case (1 failed)'] },
		'node script.mjs'
	);

	assert.match(
		source,
		/import \{ remainingRuntimeFailures2019 \} from '@utilize\/test-utils\/suite\/remainingRuntimeFailures';/
	);
	assert.match(source, /\t\t\.\.\.remainingRuntimeFailures2019,/);
	assert.match(source, /"sample\.json :: case \(1 failed\)",/);
	assert.doesNotMatch(source, new RegExp(JSON.stringify(remainingRuntimeFailures2019[0])));
});

void test('renderDialectFailures rejects a partially fixed shared list', () => {
	assert.throws(
		() =>
			renderDialectFailures({ '2019-09': [remainingRuntimeFailures2019[0]] }, 'node script.mjs'),
		/Update remainingRuntimeFailures\.ts/
	);
});

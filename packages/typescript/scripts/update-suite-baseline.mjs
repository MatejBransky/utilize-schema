import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { isCompatible, OTHER_DIALECTS } from '@utilize/test-utils/suite/compatibility';
import { loadSuiteFiles, suiteCaseKey } from '@utilize/test-utils/suite/loadSuite';
import { renderCaseModule } from '@utilize/test-utils/suite/renderCaseModule';

import { baseline } from '../test/suite/baseline.ts';
import { typecheckCases } from '../test/suite/typecheck.ts';

const root = resolve(import.meta.dirname, '..');
const suiteDirectory = join(root, 'test', 'suite');
const { generate } = await import(pathToFileURL(join(root, 'dist/index.mjs')).href);

console.log = () => {};
console.warn = () => {};

const files = loadSuiteFiles();
const gapsByDialect = {};

for (const [dialect, token] of Object.entries(OTHER_DIALECTS)) {
	const runnable = [];

	for (const file of files) {
		for (const testCase of file.cases) {
			if (!isCompatible(testCase.compatibility, token)) {
				continue;
			}

			if (testCase.tags?.includes('format-assertion')) {
				continue;
			}

			runnable.push({ testCase, key: suiteCaseKey(file, testCase) });
		}
	}

	const modules = [];
	const crashes = new Map();

	for (const { testCase, key } of runnable) {
		try {
			modules.push({
				key,
				module: await renderCaseModule(testCase, dialect, generate, `${suiteDirectory}/`),
			});
		} catch (error) {
			const message = error instanceof Error ? error.message : String(error);

			crashes.set(key, message.replaceAll(`${suiteDirectory}/`, ''));
		}
	}

	const results = await typecheckCases(modules);
	const gaps = [];
	const typeGapKeys = [];
	let passing = 0;
	let passingInstances = 0;

	for (const { key } of runnable) {
		const reasons = [];
		const crash = crashes.get(key);

		if (crash !== undefined) {
			reasons.push(`crashes: ${crash.split('\n')[0]}`);
		}

		for (const message of results.invalidModules.get(key) ?? []) {
			reasons.push(`invalid TypeScript: ${message}`);
		}

		for (const index of results.validRejected.get(key) ?? []) {
			reasons.push(`rejects valid instance ${index}`);
		}

		if (reasons.length > 0) {
			gaps.push(`${key}: ${reasons.join('; ')}`);
			continue;
		}

		if ((results.invalidAccepted.get(key) ?? []).length > 0) {
			typeGapKeys.push(key);
			continue;
		}

		passing += 1;
	}

	for (const entry of modules) {
		const rejectedValid = new Set(results.validRejected.get(entry.key) ?? []);
		const acceptedInvalid = new Set(results.invalidAccepted.get(entry.key) ?? []);

		for (const instance of entry.module.instances) {
			const failed = instance.valid
				? rejectedValid.has(instance.index)
				: acceptedInvalid.has(instance.index);

			if (!failed) {
				passingInstances += 1;
			}
		}
	}

	if (results.unattributed.length > 0) {
		throw new Error(`Unattributed diagnostics for ${dialect}: ${results.unattributed.join('; ')}`);
	}

	const recorded = baseline[dialect];

	if (
		passing !== recorded.passing ||
		gaps.length !== recorded.gaps ||
		typeGapKeys.length !== recorded.typeGaps
	) {
		throw new Error(
			`${dialect} does not match the recorded baseline: ${passing}/${runnable.length} passing, ` +
				`${gaps.length} gaps, ${typeGapKeys.length} type gaps`
		);
	}

	gapsByDialect[dialect] = { gaps: gaps.sort(), typeGaps: typeGapKeys.sort() };
	process.stdout.write(
		`${dialect}: ${passing}/${runnable.length} passing, ${gaps.length} gaps, ` +
			`${typeGapKeys.length} type gaps, ${passingInstances} instances\n`
	);
}

function renderList(values) {
	return values.map((value) => `\t\t\t${JSON.stringify(value)},`).join('\n');
}

const body = Object.entries(gapsByDialect)
	.map(
		([dialect, entry]) =>
			`\t${JSON.stringify(dialect)}: {\n\t\tgaps: [\n${renderList(entry.gaps)}\n\t\t],\n\t\ttypeGaps: [\n${renderList(entry.typeGaps)}\n\t\t],\n\t},`
	)
	.join('\n');

writeFileSync(
	join(root, 'test/suite/knownGapsByDialect.ts'),
	`// Generated by \`pnpm --filter @utilize/typescript update:suite-baseline\`; do not edit by hand.
export interface DialectGaps {
	/** Cases that crash, emit invalid TypeScript or reject a valid instance. */
	gaps: string[];
	/** Cases that differ only because an invalid instance is accepted. */
	typeGaps: string[];
}

export const knownGapsByDialect = {
${body}
} satisfies Record<string, DialectGaps>;
`
);

process.stdout.write('wrote test/suite/knownGapsByDialect.ts\n');

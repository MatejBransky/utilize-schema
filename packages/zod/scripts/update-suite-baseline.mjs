import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';
import { pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const zodPackage = join(root, 'packages/zod/package.json');
const require = createRequire(zodPackage);
const { z } = require('zod');

const suiteRoot = join(
	dirname(require.resolve('json-schema-test-suite/package.json')),
	'validation',
	'tests'
);

const { parse, Meta } = await import(
	pathToFileURL(join(root, 'packages/json-schema/dist/index.mjs')).href
);
const { generate } = await import(pathToFileURL(join(root, 'packages/zod/dist/index.mjs')).href);
const { knownFailures } = await import(
	pathToFileURL(join(root, 'packages/zod/test/suite/knownFailures.ts')).href
);

console.log = () => {};
console.warn = () => {};

function evaluate(code) {
	if (!code.includes('export ')) {
		return new Function('z', `return ${code}`)(z);
	}

	const javascript = stripTypeScriptTypes(code, { mode: 'strip' }).replace(
		/^export const /gm,
		'const '
	);

	return new Function('z', `${javascript}\nreturn Root;`)(z);
}

async function compile(schema) {
	const { root: parsedRoot } = await parse(schema, {
		cwd: suiteRoot + '/',
		fileName: 'Root.json',
	});
	const code = generate(parsedRoot, {
		importZod: false,
		customNameResolver: (candidate) => (candidate[Meta]?.parent === null ? 'Root' : undefined),
	});

	return evaluate(code);
}

const cases = new Map();
for (const file of readdirSyncSuite()) {
	const json = JSON.parse(readFileSync(join(suiteRoot, file), 'utf8'));
	for (const testCase of json.tests) {
		cases.set(`${file} :: ${testCase.description}`, { file, testCase });
	}
}

function readdirSyncSuite() {
	const files = readdirSync(suiteRoot).filter((file) => file.endsWith('.json'));

	// eslint-disable-next-line unicorn/no-array-sort -- `files` is a fresh array
	files.sort();

	return files;
}

const output = {};

for (const key of Object.keys(knownFailures)) {
	const entry = cases.get(key);

	if (!entry) {
		throw new Error(`No suite case for known failure: ${key}`);
	}

	try {
		const schema = await compile(entry.testCase.schema);
		const failures = entry.testCase.tests
			.filter((suiteTest) => schema.safeParse(suiteTest.data).success !== suiteTest.valid)
			.map((suiteTest) => suiteTest.description);

		output[key] = failures;
	} catch {
		output[key] = 'compile';
	}
}

const body = Object.entries(output)
	.map(([key, value]) => {
		if (value === 'compile') {
			return `\t${JSON.stringify(key)}: 'compile',`;
		}

		const items = value.map((description) => `\t\t${JSON.stringify(description)},`).join('\n');

		return `\t${JSON.stringify(key)}: [\n${items}\n\t],`;
	})
	.join('\n');

const file = `// Generated by \`node scripts/update-suite-baseline.mjs\`; do not edit by hand.
export type KnownFailureInstances = Record<string, string[] | 'compile'>;

export const knownFailureInstances: KnownFailureInstances = {
${body}
};
`;

writeFileSync(join(root, 'packages/zod/test/suite/knownFailureInstances.ts'), file);
process.stdout.write(`wrote ${Object.keys(output).length} entries\n`);

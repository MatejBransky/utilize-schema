import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { renderKnownFailureInstances } from '@utilize/test-utils/suite/baseline';
import { evaluateGeneratedCode, nameRootSchema } from '@utilize/test-utils/suite/evaluate';
import { loadSuiteFiles, suiteCaseKey, suiteDirectory } from '@utilize/test-utils/suite/loadSuite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const zodPackage = join(root, 'packages/zod/package.json');
const require = createRequire(zodPackage);
const { z } = require('zod');

const { parse } = await import(
	pathToFileURL(join(root, 'packages/json-schema/dist/index.mjs')).href
);
const { generate } = await import(pathToFileURL(join(root, 'packages/zod/dist/index.mjs')).href);
const { knownFailures } = await import(
	pathToFileURL(join(root, 'packages/zod/test/suite/knownFailures.ts')).href
);

console.log = () => {};
console.warn = () => {};

async function compile(schema, externalSchemas) {
	const { root: parsedRoot } = await parse(schema, {
		cwd: suiteDirectory + '/',
		fileName: 'Root.json',
		externalSchemas,
	});
	const code = generate(parsedRoot, { importZod: false, customNameResolver: nameRootSchema });

	return evaluateGeneratedCode(code, { z });
}

const cases = new Map();
for (const file of loadSuiteFiles()) {
	for (const testCase of file.cases) {
		cases.set(suiteCaseKey(file, testCase), { file: file.name, testCase });
	}
}

const output = {};

for (const key of Object.keys(knownFailures)) {
	const entry = cases.get(key);

	if (!entry) {
		throw new Error(`No suite case for known failure: ${key}`);
	}

	try {
		const schema = await compile(entry.testCase.schema, entry.testCase.externalSchemas);
		const failures = entry.testCase.tests
			.filter((suiteTest) => schema.safeParse(suiteTest.data).success !== suiteTest.valid)
			.map((suiteTest) => suiteTest.description);

		output[key] = failures;
	} catch {
		output[key] = 'compile';
	}
}

const body = renderKnownFailureInstances(output);

const file = `// Generated by \`node scripts/update-suite-baseline.mjs\`; do not edit by hand.
export type KnownFailureInstances = Record<string, string[] | 'compile'>;

export const knownFailureInstances: KnownFailureInstances = {
${body}
};
`;

writeFileSync(join(root, 'packages/zod/test/suite/knownFailureInstances.ts'), file);
process.stdout.write(`wrote ${Object.keys(output).length} entries\n`);

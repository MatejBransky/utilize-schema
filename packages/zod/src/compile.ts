import { type DialectOptions, type JSONSchema, parse } from '@utilize/json-schema';

import { readFileSync, writeFileSync } from 'fs';
import { load as loadYaml } from 'js-yaml';
import path from 'path';

import { generate, type GenerateOptions } from './generator';

export interface CompileOptions
	extends DialectOptions, Pick<GenerateOptions, 'customNameResolver' | 'schemaName' | 'typeName'> {
	input: string;
	output?: string;
	cwd?: string;
	/** Map `readOnly: true` to `.readonly()`; off by default because it changes the value type. */
	readOnlyKeyword?: boolean;
	/** Header prepended to the generated file. Pass `false` to omit it. */
	bannerComment?: string | false;
}

export interface CompileSchemaOptions
	extends DialectOptions, Pick<GenerateOptions, 'customNameResolver' | 'schemaName' | 'typeName'> {
	cwd: string;
	fileName: string;
	readOnlyKeyword?: boolean;
}

const defaultCwd = process.cwd();

export const DEFAULT_BANNER = `/* eslint-disable */
/**
 * This file was automatically generated by @utilize/zod.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSON Schema and run the generator again.
 */

`;

export async function compile(userOptions: CompileOptions) {
	const cwd = userOptions.cwd ?? defaultCwd;
	const inputPath = path.resolve(cwd, userOptions.input);
	const outputPath = path.resolve(cwd, userOptions.output ?? 'schema.generated.ts');

	const code = await compileFile(inputPath, {
		customNameResolver: userOptions.customNameResolver,
		schemaName: userOptions.schemaName,
		typeName: userOptions.typeName,
		readOnlyKeyword: userOptions.readOnlyKeyword,
		dialect: userOptions.dialect,
		fallbackDialect: userOptions.fallbackDialect,
		unknownDialect: userOptions.unknownDialect,
		keywordPolicy: userOptions.keywordPolicy,
		onDialectIssue: userOptions.onDialectIssue,
	});

	writeFileSync(outputPath, withBanner(code, userOptions.bannerComment), 'utf8');
}

/** Compiles a JSON or YAML schema file to generated code without writing anything. */
export async function compileFile(inputPath: string, options: Partial<CompileSchemaOptions> = {}) {
	return compileSchema(readSchema(inputPath), {
		cwd: path.dirname(inputPath),
		fileName: path.basename(inputPath),
		...options,
	});
}

/** Compiles an already parsed JSON Schema value to generated code. */
export async function compileSchema(schema: JSONSchema, options: CompileSchemaOptions) {
	const { root } = await parse(schema, {
		cwd: options.cwd,
		fileName: options.fileName,
		dialect: options.dialect,
		fallbackDialect: options.fallbackDialect,
		unknownDialect: options.unknownDialect,
		keywordPolicy: options.keywordPolicy,
		onDialectIssue: options.onDialectIssue,
	});

	return generate(root, {
		customNameResolver: options.customNameResolver,
		schemaName: options.schemaName,
		typeName: options.typeName,
		readOnlyKeyword: options.readOnlyKeyword,
	});
}

export function readSchema(filePath: string): JSONSchema {
	const source = readFileSync(filePath, 'utf8');

	if (/\.ya?ml$/i.test(filePath)) {
		return loadYaml(source) as JSONSchema;
	}

	return JSON.parse(source) as JSONSchema;
}

export function withBanner(code: string, bannerComment?: string | false) {
	if (bannerComment === false) {
		return code;
	}

	return `${bannerComment ?? DEFAULT_BANNER}${code}`;
}

import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, beforeEach, describe, expect, test, vi } from 'vitest';

import type { JSONSchema } from '../src';
import {
	compilePaths,
	formatAndDialectFlags,
	generatedFileBanner,
	parseForCompile,
	parseSchemaSource,
	prependBanner,
	readFormatAndDialectFlags,
	readSchema,
	schemaFileLocation,
} from '../src/node';
import type { CliIo } from '../src/node';

const io = (): CliIo & { errors: string[] } => {
	const errors: string[] = [];

	return {
		errors,
		stdout: { write: () => true },
		stderr: { write: (chunk) => errors.push(chunk) },
	};
};

describe('schema files', () => {
	let directory: string;

	beforeEach(() => {
		directory = mkdtempSync(path.join(tmpdir(), 'utilize-json-schema-'));
	});

	afterEach(() => {
		rmSync(directory, { recursive: true, force: true });
	});

	test('readSchema reads YAML by extension and JSON otherwise', () => {
		writeFileSync(path.join(directory, 'a.yaml'), 'type: string\n');
		writeFileSync(path.join(directory, 'b.YML'), 'type: number\n');
		writeFileSync(path.join(directory, 'c.json'), '{"type":"boolean"}');

		expect(readSchema(path.join(directory, 'a.yaml'))).toEqual({ type: 'string' });
		expect(readSchema(path.join(directory, 'b.YML'))).toEqual({ type: 'number' });
		expect(readSchema(path.join(directory, 'c.json'))).toEqual({ type: 'boolean' });
	});

	test('readSchema does not fall back to YAML for a .json file', () => {
		writeFileSync(path.join(directory, 'a.json'), 'type: string\n');

		expect(() => readSchema(path.join(directory, 'a.json'))).toThrow(SyntaxError);
	});

	test('parseSchemaSource reads JSON, then falls back to YAML', () => {
		expect(parseSchemaSource('{"type":"string"}')).toEqual({ type: 'string' });
		expect(parseSchemaSource('type: string\n')).toEqual({ type: 'string' });
	});
});

describe('banners', () => {
	test('generatedFileBanner names the package', () => {
		expect(generatedFileBanner('@utilize/example')).toBe(`/* eslint-disable */
/**
 * This file was automatically generated by @utilize/example.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSON Schema and run the generator again.
 */

`);
	});

	test('prependBanner uses the default, a custom banner or none', () => {
		expect(prependBanner('code', undefined, '// default\n')).toBe('// default\ncode');
		expect(prependBanner('code', '// custom\n', '// default\n')).toBe('// custom\ncode');
		expect(prependBanner('code', false, '// default\n')).toBe('code');
	});
});

describe('compile paths', () => {
	test('compilePaths resolves against cwd and defaults the output', () => {
		expect(compilePaths({ cwd: '/work', input: 'in/a.json' })).toEqual({
			inputPath: path.resolve('/work/in/a.json'),
			outputPath: path.resolve('/work/schema.generated.ts'),
		});
		expect(compilePaths({ input: 'a.json', output: 'out.ts' }, '/base')).toEqual({
			inputPath: path.resolve('/base/a.json'),
			outputPath: path.resolve('/base/out.ts'),
		});
	});

	test('schemaFileLocation splits a path into cwd and fileName', () => {
		expect(schemaFileLocation('/work/in/a.json')).toEqual({ cwd: '/work/in', fileName: 'a.json' });
	});
});

describe('parseForCompile', () => {
	const schema = {
		$schema: 'http://json-schema.org/draft-07/schema#',
		type: 'array',
		prefixItems: [{ type: 'string' }],
	} satisfies JSONSchema;

	test('prints dialect issues as warnings by default', async () => {
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});

		try {
			await parseForCompile(schema, { cwd: '/', fileName: 'Root.json' });

			expect(warn).toHaveBeenCalled();
		} finally {
			warn.mockRestore();
		}
	});

	test('passes dialect issues to onDialectIssue instead', async () => {
		const warn = vi.spyOn(console, 'warn').mockImplementation(() => {});
		const onDialectIssue = vi.fn();

		try {
			await parseForCompile(schema, { cwd: '/', fileName: 'Root.json', onDialectIssue });

			expect(onDialectIssue).toHaveBeenCalled();
			expect(warn).not.toHaveBeenCalled();
		} finally {
			warn.mockRestore();
		}
	});
});

describe('readFormatAndDialectFlags', () => {
	test('declares --format-mode with assert as default', () => {
		expect(formatAndDialectFlags['format-mode']).toEqual({ type: 'string', default: 'assert' });
	});

	test('reads the format mode and the dialect flags', () => {
		const result = readFormatAndDialectFlags(
			{ 'format-mode': 'annotate', dialect: 'draft-04', 'keyword-policy': 'error' },
			io()
		);

		expect(result).toMatchObject({
			ok: true,
			options: { formatMode: 'annotate', dialect: 'draft-04', keywordPolicy: 'error' },
		});
	});

	test('rejects an unknown format mode', () => {
		expect(readFormatAndDialectFlags({ 'format-mode': 'nope' }, io())).toEqual({
			ok: false,
			error: 'Unknown format mode "nope"; expected "annotate" or "assert".',
		});
	});

	test('reports a dialect error before a format mode error', () => {
		expect(readFormatAndDialectFlags({ 'format-mode': 'nope', dialect: 'nope' }, io())).toEqual({
			ok: false,
			error: 'Unknown dialect "nope"',
		});
	});

	test('prints dialect issues to stderr', () => {
		const cli = io();
		const result = readFormatAndDialectFlags({ 'format-mode': 'assert' }, cli);

		if (!result.ok) {
			throw new Error(result.error);
		}

		result.options.onDialectIssue?.({
			kind: 'unknown-keyword',
			message: 'Unknown keyword',
			dialect: 'draft-07',
			dialectSource: 'fallback',
			path: [],
		});

		expect(cli.errors).toEqual(['Unknown keyword (<schema>)\n']);
	});
});

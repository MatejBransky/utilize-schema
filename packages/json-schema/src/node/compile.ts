import { readFileSync } from 'node:fs';
import path from 'node:path';

import { load as loadYaml } from 'js-yaml';

import { pickDialectOptions, warnDialectIssue } from '../dialect';
import { isJSONSchemaObject } from '../model';
import type { JSONSchema } from '../model';
import { parse } from '../parser';
import type { ParseOptions } from '../parser';

/** A synchronous or asynchronous formatter applied to generated code. */
export type CodeFormatter = (code: string) => string | Promise<string>;

/** Reads a schema file: YAML for `.yaml` and `.yml`, JSON otherwise. */
export function readSchema(filePath: string): JSONSchema {
	const source = readFileSync(filePath, 'utf8');
	const schema: unknown = /\.ya?ml$/i.test(filePath) ? loadYaml(source) : JSON.parse(source);

	return requireSchemaObject(schema, filePath);
}

/** Parses schema text of unknown format, such as stdin: JSON when it parses, YAML otherwise. */
export function parseSchemaSource(source: string): JSONSchema {
	let schema: unknown;

	try {
		schema = JSON.parse(source);
	} catch {
		schema = loadYaml(source);
	}

	return requireSchemaObject(schema, 'schema source');
}

function requireSchemaObject(value: unknown, source: string): JSONSchema {
	if (!isJSONSchemaObject(value)) {
		throw new TypeError(`${source} must contain a JSON Schema object`);
	}

	return value;
}

/** The header of a generated file, naming the package that generated it. */
export function generatedFileBanner(packageName: string): string {
	return `/* eslint-disable */
/**
 * This file was automatically generated by ${packageName}.
 * DO NOT MODIFY IT BY HAND. Instead, modify the source JSON Schema and run the generator again.
 */

`;
}

/**
 * Prepends `bannerComment` to the generated code, or `defaultBanner` when it is
 * not given. `false` leaves the code without a banner.
 */
export function prependBanner(
	code: string,
	bannerComment: string | false | undefined,
	defaultBanner: string
): string {
	if (bannerComment === false) {
		return code;
	}

	return `${bannerComment ?? defaultBanner}${code}`;
}

export interface CompileLocation {
	/** Path of the JSON Schema file, resolved against `cwd`. */
	input: string;
	/** Path of the generated file, resolved against `cwd`. */
	output?: string;
	/** Base directory for `input` and `output`. */
	cwd?: string;
}

export interface CompilePaths {
	/** Absolute path of the input schema. */
	inputPath: string;
	/** Absolute path of the generated module; defaults to `schema.generated.ts`. */
	outputPath: string;
}

/** The absolute input and output paths of `compile`; the output defaults to `schema.generated.ts`. */
export function compilePaths(
	location: CompileLocation,
	defaultCwd: string = process.cwd()
): CompilePaths {
	const cwd = location.cwd ?? defaultCwd;

	return {
		inputPath: path.resolve(cwd, location.input),
		outputPath: path.resolve(cwd, location.output ?? 'schema.generated.ts'),
	};
}

export interface SchemaFileLocation {
	/** Directory the schema is parsed from. */
	cwd: string;
	/** File name relative to `cwd`. */
	fileName: string;
}

/** The `cwd` and `fileName` a schema file is parsed with, so its relative `$ref`s resolve. */
export function schemaFileLocation(filePath: string): SchemaFileLocation {
	return { cwd: path.dirname(filePath), fileName: path.basename(filePath) };
}

/**
 * Parses a schema for a generator's `compileSchema`. Unlike `parse`, dialect
 * issues are printed as warnings unless `onDialectIssue` handles them, so
 * programmatic builds still see them.
 */
export function parseForCompile(
	schema: JSONSchema,
	options: ParseOptions
): ReturnType<typeof parse> {
	return parse(schema, {
		cwd: options.cwd,
		fileName: options.fileName,
		externalSchemas: options.externalSchemas,
		...pickDialectOptions(options),
		onDialectIssue: options.onDialectIssue ?? warnDialectIssue,
	});
}
